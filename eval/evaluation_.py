def inject_character_swaps(text, noise_level=0.1):
    if len(text) < 2 or noise_level <= 0:
        return text
    text_list = list(text)
    num_swaps = max(1, int(len(text) * noise_level))
    for _ in range(num_swaps):
        idx = random.randint(0, len(text_list) - 2)
        text_list[idx], text_list[idx+1] = text_list[idx+1], text_list[idx]
    return "".join(text_list)

def parse_extraction_output(full_text, prompt_text):
    """🔥 FIXED: robust parser that isolates ONLY the model's new generation."""
    # 1. Strip the prompt out so we only look at what the model added
    if full_text.startswith(prompt_text):
        generated_part = full_text[len(prompt_text):].strip()
    else:
        # Fallback if tokenizer alters prompt formatting slightly
        generated_part = full_text.split("Target Node:")[-1].strip()

    # 2. Base models hallucinate. Stop at the very first newline.
    first_line = generated_part.split('\n')[0].strip()

    # 3. Parse strict format: "NodeName (Type: NodeClass)"
    match_strict = re.search(r'^(.*?)\s*\(\s*Type:\s*(.*?)\s*\)', first_line, re.IGNORECASE)
    if match_strict:
        return match_strict.group(1).strip(), match_strict.group(2).strip(), first_line

    # 4. Fallback: Take the whole first line, clean trailing punctuation
    raw_node = re.sub(r'[,.]+$', '', first_line).strip()
    return raw_node, "Unknown", first_line

def calculate_target_loss(context_text, target_text, current_model, current_tokenizer):
    full_text = context_text + target_text
    inputs = current_tokenizer(full_text, return_tensors="pt").to(current_model.device)

    # Tokenize context separately to find where the target begins
    context_ids = current_tokenizer(context_text, return_tensors="pt", add_special_tokens=False)["input_ids"][0]

    labels = inputs["input_ids"].clone()
    # Mask out the context so we only calculate loss on the target tokens
    mask_length = min(len(context_ids), labels.shape[1] - 1)
    labels[0, :mask_length] = -100

    with torch.no_grad():
        outputs = current_model(input_ids=inputs["input_ids"], labels=labels)
        return outputs.loss.item()

