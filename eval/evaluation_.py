# 3. MASTER EVALUATION LOOP (MODELS -> SEEDS)
# ==============================================================================
all_generated_files = []
bnb_config = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_compute_dtype=torch.bfloat16)

for base_model_path in ALL_MODELS:
    print(f"\n{'='*60}")
    print(f"🚀 INITIALIZING RUN FOR MODEL FAMILY: {base_model_path}")
    print(f"{'='*60}")

    for seed in SEEDS_TO_EVAL:
        print(f"\n  ▶️ Starting Evaluation for Seed: {seed} ...")

        # --- A. Dynamically Construct Model Name & Load Model ---
        if base_model_path == CONTROL_MODEL:
            model_name = CONTROL_MODEL
            print(f"Loading Base Control Model natively: {model_name}")

            tokenizer = AutoTokenizer.from_pretrained(CONTROL_MODEL)
            if tokenizer.pad_token is None: tokenizer.pad_token = tokenizer.eos_token

            base_model = AutoModelForCausalLM.from_pretrained(
                CONTROL_MODEL, quantization_config=bnb_config, device_map="auto"
            )
            model = base_model

        else:
            model_name = f"{base_model_path}-seed{seed}"
            print(f"Loading Base Model + applying PEFT Adapter: {model_name}...")

            tokenizer = AutoTokenizer.from_pretrained(CONFIG["base_model_name"])
            if tokenizer.pad_token is None: tokenizer.pad_token = tokenizer.eos_token

            base_model = AutoModelForCausalLM.from_pretrained(
                CONFIG["base_model_name"], quantization_config=bnb_config, device_map="auto"
            )
            model = PeftModel.from_pretrained(base_model, model_name)

        model.eval()

        # Enforce reproducibility
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)

        dataset = datasets_by_seed[seed]

        csv_results = []
        ext_metrics = {"tp": 0, "fp": 0, "fn": 0, "hallucinations": 0, "topology_violations": 0}
        rank_metrics = {"correct": 0, "factual_errors": 0, "topology_errors": 0, "hallucination_errors": 0}
        total_time = 0.0
        torch.cuda.reset_peak_memory_stats()

        # --- B. Evaluation Inner Loop ---
        for i, example in enumerate(dataset):
            ground_truth_name = example['y_name']
            ground_truth_type = example['y_type']
            source_node_processed = example['x_name']

            if CONFIG["EVAL_MODE"] == "robustness":
                source_node_processed = inject_character_swaps(source_node_processed, CONFIG["noise_level"])

            # 🔥 FIXED: Much stricter prompt to prevent babbling
            prompt = (
                "Task: Analyze the biomedical relationship and output ONLY the Target Node and its Type. "
                "Do not write explanations, exercises, or extra text.\n\n"
                f"Source Node: {source_node_processed} (Type: {example['x_type']})\n"
                f"Relationship: {example['relation']}\n"
                f"Target Node: "
            )

            start_time = time.time()

            # ----------------------------------------------------
            # PASS A: ZERO-SHOT GENERATIVE EXTRACTION
            # ----------------------------------------------------
            inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=CONFIG["max_new_tokens"], # Restricted to 20
                    pad_token_id=tokenizer.eos_token_id,
                    do_sample=False
                )

            full_text = tokenizer.decode(outputs[0], skip_special_tokens=True)
            ext_name, ext_type, raw_gen = parse_extraction_output(full_text, prompt)

            # Lowercase for exact matching (prevents false negatives due to capitalization)
            ext_name_norm = ext_name.lower() if ext_name else None
            gt_name_norm = ground_truth_name.lower()

            ext_is_correct = False
            if ext_name is None or ext_name == "":
                ext_metrics["fn"] += 1
            elif ext_name_norm not in VALID_NODES:
                ext_metrics["hallucinations"] += 1
                ext_metrics["fp"] += 1
            elif ext_name_norm in VALID_NODE_TYPES and VALID_NODE_TYPES[ext_name_norm] != ext_type and ext_type != "Unknown":
                ext_metrics["topology_violations"] += 1
                ext_metrics["fp"] += 1
            elif ext_name_norm == gt_name_norm:
                ext_metrics["tp"] += 1
                ext_is_correct = True
            else:
                ext_metrics["fp"] += 1
                ext_metrics["fn"] += 1

            # ----------------------------------------------------
            # PASS B: ADVERSARIAL GENERATIVE RANKING
            # ----------------------------------------------------
            same_type_nodes = [n for n in ontology_dict[ground_truth_type] if n != ground_truth_name]
            factual_trap = random.choice(same_type_nodes) if same_type_nodes else "Generic_Biomolecule"

            wrong_types = [t for t in ontology_dict.keys() if t != ground_truth_type]
            if wrong_types:
                random_wrong_type = random.choice(wrong_types)
                topology_trap = random.choice(ontology_dict[random_wrong_type])
                topology_trap_type = random_wrong_type
            else:
                topology_trap = f"Topology_Violation_Sim_{random.randint(1000, 9999)}"
                topology_trap_type = "Simulated_Type"

            hallucination_trap = f"BioNode_{random.randint(10000, 99999)}"

            # 🔥 FIXED: Added "(Type: ...)" to the ranking targets so the loss matches the expected schema
            target_correct = f"{ground_truth_name} (Type: {ground_truth_type})"
            target_factual = f"{factual_trap} (Type: {ground_truth_type})"
            target_topology = f"{topology_trap} (Type: {topology_trap_type})"
            target_hallucination = f"{hallucination_trap} (Type: Unknown)"

            option_mapping = {
                target_correct: "Correct",
                target_factual: "Factual_Error",
                target_topology: "Topology_Error",
                target_hallucination: "Hallucination_Error"
            }

            options = list(option_mapping.keys())
            random.shuffle(options)

            option_losses = {}
            for opt in options:
                option_losses[opt] = calculate_target_loss(prompt, opt, model, tokenizer)

            rank_pred_string = min(option_losses, key=option_losses.get)
            rank_error_type = option_mapping[rank_pred_string]

            if rank_error_type == "Correct": rank_metrics["correct"] += 1
            elif rank_error_type == "Factual_Error": rank_metrics["factual_errors"] += 1
            elif rank_error_type == "Topology_Error": rank_metrics["topology_errors"] += 1
            elif rank_error_type == "Hallucination_Error": rank_metrics["hallucination_errors"] += 1

            total_time += (time.time() - start_time)

            row_data = {
                "Source_Node": example['x_name'],
                "Relation": example['relation'],
                "Ground_Truth": ground_truth_name,
                "Ext_Predicted": ext_name if ext_name else "FAILED",
                "Ext_Is_Correct": int(ext_is_correct),
                "Raw_Output": raw_gen,  # Will now accurately contain ONLY the generated fragment
                "Rank_Predicted": rank_pred_string.split(" (Type:")[0], # Strip suffix for cleaner CSV
                "Rank_Error_Type": rank_error_type,
                "Rank_Is_Correct": int(rank_error_type == "Correct")
            }
            csv_results.append(row_data)

            if (i + 1) % 100 == 0:
                print(f"    Processed {i + 1}/{actual_eval_samples} iterations...")

        # --- C. Generate & Save Reports For This Seed ---
        N = actual_eval_samples
        max_vram_mb = torch.cuda.max_memory_allocated() / (1024 ** 2)

        ext_p = ext_metrics["tp"] / (ext_metrics["tp"] + ext_metrics["fp"]) if (ext_metrics["tp"] + ext_metrics["fp"]) > 0 else 0
        ext_r = ext_metrics["tp"] / (ext_metrics["tp"] + ext_metrics["fn"]) if (ext_metrics["tp"] + ext_metrics["fn"]) > 0 else 0
        ext_f1 = 2 * (ext_p * ext_r) / (ext_p + ext_r) if (ext_p + ext_r) > 0 else 0
        global_rank_acc = (rank_metrics["correct"] / N) * 100

        results_df = pd.DataFrame(csv_results)

        class_metrics = []
        for relation, group in results_df.groupby('Relation'):
            count = len(group)
            ext_correct = group['Ext_Is_Correct'].sum()
            rank_correct = group['Rank_Is_Correct'].sum()
            class_metrics.append({
                "Relation": relation,
                "N_Samples": count,
                "Extraction_Acc_%": round((ext_correct / count) * 100, 2),
                "Ranking_Acc_%": round((rank_correct / count) * 100, 2)
            })

        class_df = pd.DataFrame(class_metrics).sort_values(by="N_Samples", ascending=False)
        class_df_string = class_df.to_string(index=False)

        report_text = f"""
        ==================================================
        🏆 RESULTS
        MODEL: {model_name}
        MODE: {CONFIG['EVAL_MODE'].upper()} | SEED: {seed}
        ==================================================
        ⏱️ Total Evaluation Windows: {total_time:.2f} seconds
        💾 Operational VRAM Limits:   {max_vram_mb:.2f} MB

        [MODALITY 1: ZERO-SHOT GENERATIVE EXTRACTION]
        📊 Token F1 Metrics Space:    {ext_f1:.4f}
        🚨 Vocabulary Hallucinations: {(ext_metrics["hallucinations"] / N) * 100:.2f}%
        🔗 Structural Schema Faults:  {(ext_metrics["topology_violations"] / N) * 100:.2f}%

        [MODALITY 2: ADVERSARIAL GENERATIVE RANKING]
        ✅ Log-Likelihood Accuracy:   {global_rank_acc:.2f}%
        🔍 Factual Vector Distortions: {(rank_metrics["factual_errors"] / N) * 100:.2f}%
        🔗 Topology Matrix Violations:{(rank_metrics["topology_errors"] / N) * 100:.2f}%
        🚨 Synthesized Entity Ingestion:{(rank_metrics["hallucination_errors"] / N) * 100:.2f}%
        ==================================================

        📈 CLASS-WISE METRIC SEPARATION DECOUPLING:
        {class_df_string}
        """

        if base_model_path == CONTROL_MODEL:
            file_prefix = f"olusegunola_phi-1.5-base-seed{seed}"
        elif "phi-3" in base_model_path:
            file_prefix = f"olusegunola_phi-3-base-seed{seed}"
        else:
            file_prefix = f"{base_model_path.replace('/', '_')}-seed{seed}"

        txt_filename = f"{file_prefix}_{CONFIG['EVAL_MODE']}_report.txt"
        csv_filename = f"{file_prefix}_{CONFIG['EVAL_MODE']}_data.csv"

        with open(txt_filename, "w", encoding="utf-8") as f:
            f.write(report_text)
        results_df.to_csv(csv_filename, index=False)

        all_generated_files.extend([txt_filename, csv_filename])
        print(f"  ✅ Saved files: {txt_filename} & {csv_filename}")

        # --- D. STRICT MEMORY MANAGEMENT ---
        print(f"\n🧹 Sweeping memory to prevent Out-Of-Memory errors for next seed/model...")
        del model
        del base_model
        del tokenizer
        gc.collect()
        torch.cuda.empty_cache()
        print("✅ Memory cleared. Ready for next run.\n")

